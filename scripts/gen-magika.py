#!/usr/bin/env python3
"""Generate core/src/magika_table.rs and copy the Magika model from the
magika crate's source (Apache-2.0, Google): grove runs the model itself on
tract (pure Rust), so it needs the label order, each type's info, and the
thresholds / overwrite map. Usage: gen-magika.py PATH/TO/magika-X.Y.Z"""
import re, sys, shutil, pathlib
src = pathlib.Path(sys.argv[1]) / "src"
content = (src / "content.rs").read_text()
model = (src / "model.rs").read_text()

# TypeInfo statics: NAME -> dict
infos = {}
for m in re.finditer(r'static (\w+): TypeInfo = TypeInfo \{(.*?)\n\};', content, re.S):
    body = m.group(2)
    get = lambda k: re.search(k + r': "((?:[^"\\]|\\.)*)"', body).group(1)
    exts = re.findall(r'"([^"]*)"', re.search(r'extensions: &\[(.*?)\]', body, re.S).group(1))
    infos[m.group(1)] = dict(label=get("label"), mime=get("mime_type"), group=get("group"), desc=get("description"),
                             exts=exts, text="is_text: true" in body)
# ContentType variants in enum order, and each one's info static.
ct_body = re.search(r'pub enum ContentType \{(.*?)\n\}', content, re.S).group(1)
ct_order = re.findall(r'^\s{4}(\w+),', ct_body, re.M)
ct_info = dict(re.findall(r'ContentType::(\w+) => &(\w+),', content))
# Label variants in model output order, and label -> ContentType.
lab_body = re.search(r'enum Label \{(.*?)\n\}', model, re.S).group(1)
labels = re.findall(r'^\s{4}(\w+),', lab_body, re.M)
lab_ct = dict(re.findall(r'Label::(\w+) => ContentType::(\w+),', model))
thr = [float(x) for x in re.search(r'const THRESHOLDS: \[f32; ContentType::SIZE\] = \[(.*?)\];', model, re.S).group(1).split(',') if x.strip()]
ow = re.findall(r'ContentType::(\w+)', re.search(r'const OVERWRITE_MAP: \[ContentType; ContentType::SIZE\] = \[(.*?)\];', model, re.S).group(1))
assert len(thr) == len(ct_order) == len(ow), (len(thr), len(ct_order), len(ow))
ct_index = {c: i for i, c in enumerate(ct_order)}

def info_of(ct):
    return infos[ct_info[ct]]
def lit(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

out = ["// Generated by scripts/gen-magika.py from the magika crate (Apache-2.0,",
       "// Google LLC): Magika's labels in model output order. Do not edit.", "",
       "pub struct Label { pub label: &'static str, pub mime: &'static str, pub group: &'static str, pub description: &'static str,",
       "    pub extensions: &'static [&'static str], pub is_text: bool, pub threshold: f32, pub overwrite: &'static str }", "",
       f"pub const LABELS: [Label; {len(labels)}] = ["]
for l in labels:
    ct = lab_ct[l]
    i = info_of(ct)
    k = ct_index[ct]
    out.append(f"    Label {{ label: {lit(i['label'])}, mime: {lit(i['mime'])}, group: {lit(i['group'])}, description: {lit(i['desc'])}, "
               f"extensions: &[{', '.join(lit(e) for e in i['exts'])}], is_text: {'true' if i['text'] else 'false'}, "
               f"threshold: {thr[k]}, overwrite: {lit(info_of(ow[k])['label'])} }},")
out.append("];")
pathlib.Path(__file__).resolve().parent.parent.joinpath("core/src/magika_table.rs").write_text("\n".join(out) + "\n")
shutil.copy(src / "model.onnx", pathlib.Path(__file__).resolve().parent.parent / "core/data/magika/standard_v3_3.onnx")
print(len(labels), "labels")
